import { createAdvancedCreateConfigRoutes } from './routes/advancedCreateConfig.js';
import { resumeLocalProviderPolls } from './services/create/creationJob.js';
import { createVisitPulseQueries } from "./db/visitPulse.js";
import { startProcessSchedules } from "./services/schedule/processSchedules.js";
import createBlogRoutes from './routes/blog.js';
import { createBlogAdminRoutes } from './routes/blogAdmin.js';
import createShareRoutes from './routes/share.js';
import createCreationExportRoutes from './routes/creationExports.js';
import { createWatermarkedVideoCache } from './services/create/watermarkedVideoCache.js';
import createQrRoutes from './routes/qr.js';
import createSeoRoutes from './routes/seo.js';
import { createWelcomeMailRoutes } from './routes/welcomeMail.js';
import { createBillingRoutes } from './routes/billing.js';
import { createWorkerJobRoutes } from './routes/workerJobs.js';
import { createPolicyRoutes } from './routes/policy.js';
import { createSiteApiRoutes } from './routes/siteApi.js';
import { createKioskRoutes } from './routes/kiosk.js';
import { createProviderRoutes } from './routes/provider.js';
import { createChatInviteRoutes } from './routes/chatInvites.js';
import { createUnhandledRequestLog } from './db/unhandledRequests.js';
import { createUnhandledRequestMiddleware } from './routes/middleware/unhandledRequest.js';

// Supabase Realtime needs a WebSocket implementation on Node 20.
if (!globalThis.WebSocket) globalThis.WebSocket = WebSocket;

const port = Number(process.env.PORT || 3000);
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const bindHost = process.env.NODE_ENV === "production" ? "0.0.0.0" : "127.0.0.1";
const pagesDir = path.join(__dirname, "pages");
const app = express();
const db = createDb();

app.set("trust proxy", true);
app.use("/api/webhooks/stripe", express.raw({ type: "application/json" }));
app.use("/api/auth", express.json({ limit: "1mb" }));
app.use(/^\/api\/create\/images\/[^/]+\/fit-thumbnail$/, express.json({ limit: "12mb" }));
app.use("/api", express.json({ limit: "1mb" }));
app.use("/api/notifications", express.urlencoded({ extended: false }));
app.use("/oauth/token", express.json({ limit: "64kb" }));
app.use('/oauth',express.urlencoded({extended:false}));
app.use(cookieParser());
app.use(clientIdMiddleware);
app.use(apiHostBoundary);
app.use(shareHostBoundary);
app.use(createFaviconRoutes({ publicDir: path.join(__dirname, "../public") }));
app.use(createAuthMiddleware(db.sessions, db.users));
app.use(apiKeyBearerMiddleware(db.account.queries));app.use(integrationBearerMiddleware());
app.use(createWelcomeGate(db.account.queries));
app.use(createVisitPulseMiddleware({ failOpen: true }));
// The app also serves the public profile/edited-image compatibility
// path. The CDN host serves the same route through createCdnRoutes.
app.use("/api/images/generic", createFilesCors(), createGenericRoutes(db.genericFiles, db.users));
app.use(createCdnHostBoundary(createCdnRoutes({ profileFiles: db.profileFiles, genericFiles: db.genericFiles, users: db.users })));
const challengeDependencies = { ...db.account, queries: { ...db.account.queries, ...createChallengeQueries(db.account.client) } };
app.use(createChallengeActionsRoutes(challengeDependencies));
app.use(createChallengesRoutes(challengeDependencies));
app.use(createFeedRoutes({ queries: { ...db.account.queries, ...createFeedQueries(db.account.client) } }));
const challengeCreations = createChallengeCreationRoutes(challengeDependencies);
app.use(challengeCreations);
app.use(createThreadsRoutes({ threads: db.threads }));
app.use(createRealtimeAuthRoutes({ realtimeAuth: db.realtimeAuth }));
app.use(createYoutubeRoutes());
app.use(createSunoRoutes());
app.use(createXRoutes());
app.use(createPolicyRoutes());
app.use(createBillingRoutes({ client: db.account.client, credits: db.credits, adjust: db.create.queries.updateUserCreditsBalance.run }));
app.use(createWorkerJobRoutes({ client: db.account.client, feedQueries: createFeedQueries(db.account.client), pulseQueries: createVisitPulseQueries(db.account.client) }));
app.use(createSiteApiRoutes({ client: db.account.client }));
app.use(createKioskRoutes({ client: db.account.client }));
app.use(createProviderRoutes({ client: db.account.client }));
app.use(createChatInviteRoutes({ client: db.account.client }));
app.use(createTryRoutes(db.account));
app.use(createHelpRoutes({pagesDir}));
app.use(createAdminProfileRoutes(db.account));
app.use(createAdminUsersRoutes({ client: db.account.client, users: db.users, storage: db.account.storage }));
app.use(createAdminTodoRoutes({ users: db.users }));
app.use(createAdminToolsRoutes({ client: db.account.client, users: db.users, servers: db.servers, queries: { ...db.account.queries, ...createFeedQueries(db.account.client) } }));
app.use(createProfileRoutes(db.account));
app.use(createProfileBrowseRoutes(db.account));
app.use(createFollowsRoutes(db.account));
app.use(createPresenceRoutes(db.account));
app.use(createIntegrationRoutes(db.account));
app.use(createGooglePhotosRoutes(db.account));
const watermarkedVideoCache = createWatermarkedVideoCache({ storage: db.create.storage });
app.use(createVynlyRoutes({ ...db.account, watermarkedVideoCache, comments: db.comments }));
app.use(createAppDataRoutes({ users: db.users, credits: db.credits, notifications: db.notifications, servers: db.servers }));
app.use(createAdvancedCreateConfigRoutes());
app.use(createCreateRoutes(db.create));
app.use(createRepairRoutes(db.create));
app.use(createGroupV2Routes(db.create));
app.use(createCreationExportRoutes({ queries: db.create.queries, storage: db.create.storage, watermarkedVideoCache }));
app.use(createQrRoutes());
app.use(createShareRoutes({ queries: db.create.queries, storage: db.create.storage, creations: db.creations }));
app.use(createLibraryRoutes(db.library));
app.use(createLibraryFoldersRoutes(db.library));
app.use(createAudioClipsRoutes(db.library));
app.use(createSuggestRoutes({ queries: db.suggestions }));
app.use(createExploreRoutes({ explore: db.explore, users: db.users }));
app.use(createHomeLatestRoutes({ homeLatest: db.homeLatest, users: db.users, creations: db.creations }));
app.use(createCommentsRoutes({ comments: db.comments, users: db.users, creations: db.creations }));
app.use(createCreationsRoutes({ creations: db.creations, users: db.users, createQueries: db.create.queries, createStorage: db.create.storage, appendChallengeEligibility: challengeCreations.appendEligibility }));
app.use(createAuthRoutes({ users: db.users, sessions: db.sessions }));
app.use(createBlogRoutes({ client: db.account.client, users: db.users, pagesDir }));
app.use(createBlogAdminRoutes({ client: db.account.client }));
app.use(createSeoRoutes());
app.use(createWelcomeMailRoutes({ client: db.account.client }));
const reportsRoutes = createReportsRoutes();
if (reportsRoutes) app.use(reportsRoutes);
const financeRoutes = createFinanceRoutes({ client: db.account.client });
if (financeRoutes) app.use(financeRoutes);
app.use(createAdminPageRoutes({ pagesDir, users: db.users, sessions: db.sessions }));
app.use(createPageRoutes({ pagesDir, users: db.users }));
app.use(express.static(path.join(__dirname, "../public")));
app.use(createUnhandledRequestMiddleware({ log: createUnhandledRequestLog({ client: db.account.client }) }));
app.use((error, req, res, next) => {
	console.error("[parascene] request failed", error);
	if (res.headersSent) return next(error);
	res.status(500).json({ error: "Internal server error" });
});

app.listen(port, bindHost, () => {
	console.log(`Parascene: http://localhost:${port}/`);
	console.log(`[parascene] bound to ${bindHost}:${port}`);
	void resumeLocalProviderPolls(db.create).catch(error => console.error("[parascene] Create poll recovery failed", error));
	startProcessSchedules({ client: db.account.client });
});
